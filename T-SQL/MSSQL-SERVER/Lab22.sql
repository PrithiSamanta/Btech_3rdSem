--Part � A: 
--1. Display top 3 highest amount orders. 
WITH HIGH_ORDERS AS
(
SELECT AMOUNT,ROW_NUMBER() OVER(ORDER BY AMOUNT DESC) RN
FROM CUSTOMER_ALL
)
SELECT AMOUNT
FROM HIGH_ORDERS
WHERE RN<=3

--2. Display second highest order amount. 
WITH HIGH_ORDERS AS
(
SELECT AMOUNT,ROW_NUMBER() OVER(ORDER BY AMOUNT DESC) RN
FROM CUSTOMER_ALL
)
SELECT AMOUNT
FROM HIGH_ORDERS
WHERE RN=2

--3. Display customers whose order amount is greater than category average amount. 
WITH HIGH_ORDERS AS
(
SELECT CNAME,AMOUNT,AVG(AMOUNT) OVER(PARTITION BY CATEGORY) AVG_CAT
FROM CUSTOMER_ALL
)
SELECT CNAME
FROM HIGH_ORDERS
WHERE AMOUNT>AVG_CAT

--4. Display categories having average amount greater than 30000.
WITH CATEGORIES AS
(
SELECT CATEGORY,AVG(AMOUNT) AVG_AMT
FROM CUSTOMER_ALL
GROUP BY CATEGORY
)
SELECT CATEGORY
FROM CATEGORIES
WHERE AVG_AMT>30000

--5. Display highest amount order from each category.
WITH CATEGORIES AS
(
SELECT CATEGORY,AMOUNT,RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT) RK
FROM CUSTOMER_ALL
)
SELECT CATEGORY,AMOUNT
FROM CATEGORIES
WHERE RK=1

--6. Display lowest amount order from each category. 
WITH CATEGORIES AS
(
SELECT CATEGORY,AMOUNT,RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT) RK
FROM CUSTOMER_ALL
)
SELECT CATEGORY,AMOUNT
FROM CATEGORIES
WHERE RK=1

--7. Display categories having more than 3 orders.
WITH CATEGORIES AS
(
SELECT CATEGORY,COUNT(ORDERID) ORDERS
FROM CUSTOMER_ALL
GROUP BY CATEGORY
)
SELECT CATEGORY,ORDERS
FROM CATEGORIES
WHERE ORDERS>3

--8. Display city-wise total order amount. 
WITH CITY_WISE AS
(
SELECT CITY,SUM(AMOUNT) TOTAL_AMT
FROM CUSTOMER_ALL
GROUP BY CITY
)
SELECT CITY,TOTAL_AMT
FROM CITY_WISE

--9. Display category having highest average order amount.
WITH CATEGORIES AS
(
SELECT CATEGORY,AVG(AMOUNT) AVG_AMT
FROM CUSTOMER_ALL
GROUP BY CATEGORY
),
AVG_CAT AS
(
SELECT CATEGORY,RANK() OVER(ORDER BY AVG_AMT DESC) RK_AMT
FROM CATEGORIES
)
SELECT CATEGORY
FROM AVG_CAT
WHERE RK_AMT=1

--10. Display cumulative order amount in ascending order of amount. 
WITH CUM_ORDER AS
(
SELECT SUM(AMOUNT) OVER(ORDER BY AMOUNT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) C_AMT
FROM CUSTOMER_ALL
)
SELECT C_AMT
FROM CUM_ORDER

 
