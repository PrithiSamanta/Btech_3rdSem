--11. Display category-wise top 2 highest amount orders. 
WITH CATEGORIES AS
(
SELECT ORDERID,CNAME,AMOUNT,CATEGORY,DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC) DK
FROM CUSTOMER_ALL
)
SELECT ORDERID,CNAME,AMOUNT,CATEGORY,DK
FROM CATEGORIES
WHERE DK<=2

--12. Display customers whose amount is closest to category average amount. 
WITH CATEGORIES AS
(
SELECT CNAME,AMOUNT,CATEGORY,AVG(AMOUNT) OVER(PARTITION BY CATEGORY) C_AVG
FROM CUSTOMER_ALL
),
CLOSEST AS
(
SELECT CNAME,AMOUNT,CATEGORY,RANK() OVER(PARTITION BY CATEGORY ORDER BY ABS(AMOUNT-C_AVG))  C_AMT
FROM CATEGORIES
)
SELECT CNAME,AMOUNT,CATEGORY,C_AMT
FROM CLOSEST
WHERE C_AMT=1

--13. Display previous, current and next order amount together.
WITH PRE_CURR_NEXT AS
(
SELECT ORDERID,CNAME,LAG(AMOUNT) OVER(ORDER BY AMOUNT) PRE_AMT,AMOUNT,LEAD(AMOUNT) OVER(ORDER BY AMOUNT) NEXT_AMT
FROM CUSTOMER_ALL
)
SELECT *
FROM PRE_CURR_NEXT

--14. Display customers whose amount is greater than previous customer's amount.
WITH PRE_CURR AS
(
SELECT ORDERID,CNAME,LAG(AMOUNT) OVER(ORDER BY AMOUNT) PRE_AMT,AMOUNT
FROM CUSTOMER_ALL
)
SELECT *
FROM PRE_CURR
WHERE AMOUNT>PRE_AMT

--15. Display customers whose rank and dense rank are different.
WITH RANK_DRANK AS
(
SELECT ORDERID,CNAME,AMOUNT,RANK() OVER(ORDER BY AMOUNT) RK,DENSE_RANK() OVER(ORDER BY AMOUNT) DR
FROM CUSTOMER_ALL
)
SELECT *
FROM RANK_DRANK
WHERE RK<>DR
 
