--Implement AFTER Triggers for Automatic Execution After Data Operations 
--EMPLOYEE_LOG (LOGID, EID, OLDVALUE, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE) 
--From the table EMPLOYEE perform the following queries:  
--Part – A: 
--1. Create trigger for printing message after employee record insertion. 
CREATE TRIGGER TR_INS_MSG
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
DECLARE @NAME VARCHAR(30)
SELECT @NAME=FIRSTNAME
FROM inserted
PRINT @NAME+' INSERTED'
END

--2. Create trigger for printing message after employee record update.
CREATE OR ALTER TRIGGER TR_UPDATE_MSG
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
PRINT 'RECORD UPDATED'
END

--3. Create trigger for printing message after employee record deletion.
CREATE TRIGGER TR_DEL_MSG
ON EMPLOYEE
AFTER DELETE
AS
BEGIN
DECLARE @NAME VARCHAR(30)
SELECT @NAME=FIRSTNAME
FROM deleted
PRINT @NAME+' DELETED'
END

--4. Create trigger for printing message after employee salary increment.
CREATE OR ALTER TRIGGER TR_SAL_INCRE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
DECLARE @SAL1 VARCHAR(30),@SAL2 VARCHAR(30)
SELECT @SAL2=SALARY
FROM inserted
SELECT @SAL1=SALARY
FROM deleted
IF @SAL2 > @SAL1
BEGIN
PRINT 'SALARY INCREASED FROM '+@SAL1+' TO '+@SAL2
END
END

--5. Create trigger for automatically converting CITY names into uppercase during insertion. 
CREATE OR ALTER TRIGGER TR_CITY_UPPER
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
DECLARE @CITY VARCHAR(30)
SELECT @CITY=CITY
FROM inserted
UPDATE EMPLOYEE
SET CITY=UPPER(@CITY)
WHERE CITY=@CITY
END

