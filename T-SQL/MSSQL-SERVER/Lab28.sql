END

--7. Create trigger for automatically setting CITY as 'RAJKOT' if no city value is entered during employee 
--insertion.
CREATE OR ALTER TRIGGER TR_DFLT_CITY
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
DECLARE @CITY VARCHAR(30)
SELECT @CITY=CITY
FROM inserted
IF @CITY IS NULL
BEGIN
UPDATE EMPLOYEE
SET CITY='RAJKOT'
WHERE CITY=@CITY
END
END

--8. Create trigger for automatically adding current year in JOININGYEAR if no value is entered.
CREATE OR ALTER TRIGGER TR_DFLT_YEAR
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
DECLARE @YEAR VARCHAR(30)
SELECT @YEAR=JOININGYEAAR
FROM inserted
IF @YEAR IS NULL
BEGIN
UPDATE EMPLOYEE
SET JOININGYEAAR=DATEPART(YYYY,GETDATE())
WHERE JOININGYEAAR=@YEAR
END
END

