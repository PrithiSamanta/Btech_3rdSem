CREATE OR ALTER TRIGGER TR_EMP_INSRT_LOG
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
INSERT INTO EMPLOYEE_INSERT_LOG
SELECT * FROM inserted
END

--13. Create trigger for storing old and new FIRSTNAME values after employee name update into 
--NAME_CHANGE_LOG table. 
CREATE TABLE NAME_CHANGE_LOG
(OLD_NAME VARCHAR(30),NEW_NAME VARCHAR(30))

CREATE OR ALTER TRIGGER TR_NM_UPDT
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
DECLARE @ONAME VARCHAR(30),@NNAME VARCHAR(30)
SELECT @ONAME=FIRSTNAME FROM deleted
SELECT @NNAME=FIRSTNAME FROM inserted
IF @ONAME!=@NNAME
BEGIN
INSERT INTO NAME_CHANGE_LOG
VALUES(@ONAME,@NNAME)
END
END

