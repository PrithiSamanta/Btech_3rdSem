--Part – C: 
--11. Create trigger for storing updated employee details such as EID, old salary, new salary, old department, 
--new department, and update date into EMPLOYEE_UPDATE_LOG table.
CREATE TABLE EMPLOYEE_UPDATE_LOG
(EID INT,OLD_SALARY DECIMAL(10,2),NEW_SALARY DECIMAL(10,2),
OLD_DEPT VARCHAR(30),NEW_DEPT VARCHAR(30),UPDATE_DATE DATETIME)

CREATE OR ALTER TRIGGER TR_EMP_UPDT_LOG
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
DECLARE @EID INT,@OSAL VARCHAR(30),@NSAL VARCHAR(30),@ODEPT VARCHAR(30),@NDEPT VARCHAR(30)
SELECT @EID=EID,@OSAL=SALARY,@ODEPT=DEPARTMENT
FROM deleted
SELECT @NSAL=SALARY,@NDEPT=DEPARTMENT
FROM inserted
INSERT INTO EMPLOYEE_UPDATE_LOG
VALUES(@EID,@OSAL,@NSAL,@ODEPT,@NDEPT,GETDATE())
END

--12. Create trigger for storing newly inserted employee details with insertion date into 
--EMPLOYEE_INSERT_LOG table.
CREATE TABLE EMPLOYEE_INSERT_LOG
(EID INT,FIRSTNAME VARCHAR(30),LASTNAME VARCHAR(30),DEPARTMENT VARCHAR(30),SALARY DECIMAL(10,2),
