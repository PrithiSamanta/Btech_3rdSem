--2. Create INSTEAD OF DELETE trigger to prevent deletion of employee records and store deleted data into 
--EMPLOYEE_LOG table. 
CREATE TABLE EMPLOYEE_LOG (LOGID INT IDENTITY(1,1) PRIMARY KEY, EID INT, OLDVALUE VARCHAR(30),
NEWVALUE VARCHAR(30), FIELDNAME VARCHAR(30), OPERATIONTYPE VARCHAR(30), LOGDATE DATETIME)

CREATE TRIGGER TR_DEL_EMP
ON EMPLOYEE
INSTEAD OF DELETE
AS
BEGIN
DECLARE @EID INT,@NAME VARCHAR(30)
SELECT @EID=EID, @NAME=FIRSTNAME 
FROM deleted
INSERT INTO EMPLOYEE_LOG(EID,OLDVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
VALUES(@EID,@NAME,'FIRSTNAME','DELETE',GETDATE())
END

--3. Create INSTEAD OF trigger to log all operations on EMPLOYEE table (INSERT/UPDATE/DELETE) into 
--EMPLOYEE_LOG table. 
CREATE OR ALTER TRIGGER TR_INS_EMP
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
DECLARE @EID INT,@NAME VARCHAR(30)
SELECT @EID=EID, @NAME=FIRSTNAME 
FROM inserted
INSERT INTO EMPLOYEE_LOG(EID,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
VALUES(@EID,@NAME,'FIRSTNAME','INSERT',GETDATE())
END

CREATE OR ALTER TRIGGER TR_UPD_EMP
ON EMPLOYEE
INSTEAD OF UPDATE
AS
BEGIN
DECLARE @EID INT,@ONAME VARCHAR(30),@NNAME VARCHAR(30)
SELECT @EID=EID, @NNAME=FIRSTNAME 
FROM inserted
SELECT @EID=EID, @ONAME=FIRSTNAME 
FROM deleted
INSERT INTO EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
VALUES(@EID,@ONAME,@NNAME,'FIRSTNAME','UPDATE',GETDATE())
END
 
