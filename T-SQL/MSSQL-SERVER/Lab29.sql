--11. Create INSTEAD OF INSERT trigger to prevent insertion of students whose SPI is greater than 10 or less 
--than 0. 
CREATE OR ALTER TRIGGER TR_INS_INVA_SPI
ON STUDENT
INSTEAD OF INSERT
AS
BEGIN
DECLARE @SPI DECIMAL(4,2)
SELECT @SPI=SPI FROM inserted
IF @SPI>10 OR @SPI<0
PRINT 'INVALID SPI'
ELSE 
BEGIN
INSERT INTO STUDENT
SELECT * FROM inserted
END
END

